import { render, screen } from "@testing-library/react";
import { describe, expect, it, vi } from "vitest";
import { MarkdownDocumentViewer } from "./markdown-document-viewer";

describe("MarkdownDocumentViewer", () => {
  it("omits the empty header generated by Excel conversion without losing worksheet rows", () => {
    const { container } = render(
      <MarkdownDocumentViewer
        content={"|  |  |\n| --- | --- |\n| Nietzsche concept comparison |  |\n| Concept | Summary |\n| Genealogy | History of values |"}
      />,
    );

    expect(container.querySelector("thead")).toBeNull();
    expect(screen.getAllByRole("row")).toHaveLength(3);
    expect(screen.getByRole("cell", { name: "Nietzsche concept comparison" })).toBeTruthy();
    expect(screen.getByRole("cell", { name: "Concept" })).toBeTruthy();
    expect(screen.getByRole("cell", { name: "Genealogy" })).toBeTruthy();
  });

  it("keeps partially empty and image-alt table headers", () => {
    const { container, rerender } = render(
      <MarkdownDocumentViewer content={"| Concept |  |\n| --- | --- |\n| Genealogy | Value history |"} />,
    );
    expect(screen.getAllByRole("columnheader")).toHaveLength(2);
    expect(screen.getByRole("columnheader", { name: "Concept" })).toBeTruthy();

    rerender(
      <MarkdownDocumentViewer content={"| ![Diagram](https://example.com/image.png) |\n| --- |\n| Genealogy |"} />,
    );
    expect(container.querySelector("thead")).not.toBeNull();
    expect(screen.getByRole("columnheader", { name: "Diagram" })).toBeTruthy();
    expect(container.querySelector("img")).toBeNull();
  });

  it("uses the chat table wrapper that resets the inner table's top margin", () => {
    render(
      <MarkdownDocumentViewer content={"| Concept | Summary |\n| --- | --- |\n| Genealogy | History of values |"} />,
    );

    const region = screen.getByRole("region", { name: "Scrollable table" });
    expect(region.classList.contains("markdown-table-wrapper")).toBe(true);
    expect(region.getAttribute("tabindex")).toBe("0");
    expect(screen.getByRole("table").parentElement).toBe(region);
    expect(screen.getByRole("columnheader", { name: "Concept" }).className).toBe("");
  });

  it("preserves Markdown table column alignment like chat", () => {
    render(
      <MarkdownDocumentViewer content={"| Concept | Count |\n| :--- | ---: |\n| Genealogy | 3 |"} />,
    );

    expect(screen.getByRole("columnheader", { name: "Count" }).style.textAlign).toBe("right");
    expect(screen.getByRole("cell", { name: "3" }).style.textAlign).toBe("right");
  });

  it("inherits chat typography for paragraphs and list items without desktop size overrides", () => {
    const { container } = render(
      <MarkdownDocumentViewer content={"Source paragraph\n\n- Source item"} />,
    );
    const typography = container.querySelector(".typeset.typeset-chat");
    expect(typography).not.toBeNull();
    expect(typography?.querySelector("p")?.className).not.toMatch(/text-(sm|base)|leading-/);
    expect(typography?.querySelector("li")?.className).not.toMatch(/text-(sm|base)|leading-/);
    expect(typography?.className).not.toContain("sm:text-base");
  });

  it("renders genuine markdown headings, lists, blockquotes, and tables", () => {
    const markdownContent = [
      "# Main Title",
      "## Sub Title",
      "This is a paragraph with **bold** text.",
      "> Quote block",
      "- Item 1",
      "- Item 2",
    ].join("\n\n");

    const { container } = render(<MarkdownDocumentViewer content={markdownContent} />);

    expect(screen.getByRole("heading", { level: 1, name: /Main Title/ })).toBeTruthy();
    expect(screen.getByRole("heading", { level: 2, name: /Sub Title/ })).toBeTruthy();
    expect(container.querySelector("blockquote")).not.toBeNull();
    expect(container.querySelector("ul")).not.toBeNull();
    expect(container.querySelector("strong")).not.toBeNull();
  });

  it("handles citation locator by symbol in static mode", () => {
    const scrollIntoViewMock = vi.fn();
    window.HTMLElement.prototype.scrollIntoView = scrollIntoViewMock;

    const content = [
      "# Introduction",
      "Intro text",
      "## Deep Architecture",
      "Architecture details",
    ].join("\n\n");

    const { rerender } = render(
      <MarkdownDocumentViewer content={content} selectedLocator={null} />,
    );

    rerender(
      <MarkdownDocumentViewer
        content={content}
        selectedLocator={{ symbol: "Deep Architecture" }}
      />,
    );

    expect(scrollIntoViewMock).toHaveBeenCalled();
  });

  it.each([
    { slideNumber: 2 },
    { startOffsetMs: 1200, endOffsetMs: 2400 },
    { sheetName: "Sheet 1", cellRange: "A1:B2" },
    { imageRegion: { x: 0.1, y: 0.2, width: 0.3, height: 0.4 } },
  ])("keeps Markdown readable with unsupported exact locator %j", (locator) => {
    render(<MarkdownDocumentViewer content="# Extracted content" selectedLocator={locator} />);
    expect(screen.getByRole("heading", { name: "Extracted content" })).toBeTruthy();
  });

  it.each([
    {
      name: "timestamp",
      rawText: "Opening\n\nCited transcript words",
      locator: { startOffsetMs: 1200, endOffsetMs: 2400 },
      segmentContent: "Cited transcript words",
      expectedHighlight: true,
    },
    {
      name: "slide",
      rawText: "Introduction\n\nSlide three text",
      locator: { slideNumber: 3 },
      segmentContent: "Slide three text",
      expectedHighlight: true,
    },
    {
      name: "missing segment content",
      rawText: "Introduction\n\nVisible text",
      locator: { slideNumber: 3 },
      segmentContent: "Text absent from source",
      expectedHighlight: false,
    },
    {
      name: "ambiguous segment content",
      rawText: "Repeated text\n\nRepeated text",
      locator: { startOffsetMs: 1200 },
      segmentContent: "Repeated text",
      expectedHighlight: false,
    },
  ])("maps $name only to unique exact Markdown content", ({
    rawText,
    locator,
    segmentContent,
    expectedHighlight,
  }) => {
    window.HTMLElement.prototype.scrollIntoView = vi.fn();
    const { container } = render(
      <MarkdownDocumentViewer
        content={rawText}
        selectedLocator={locator}
        segments={[{ content: segmentContent, locator }]}
      />,
    );

    if (!expectedHighlight) {
      expect(container.querySelector(".ring-2")).toBeNull();
    } else {
      expect(screen.getByText(segmentContent).classList.contains("ring-2")).toBe(true);
    }
  });

  it("preserves ordinary Markdown links in static content", () => {
    render(
      <MarkdownDocumentViewer
        content={"[An ordinary link](https://example.com)\n\nAnother paragraph."}
      />,
    );
    expect(screen.getByRole("link", { name: "An ordinary link" }).getAttribute("href")).toBe(
      "https://example.com",
    );
  });

  it("renders image alt text without mounting an embedded preview", () => {
    const { container } = render(
      <MarkdownDocumentViewer content="![Extracted diagram](https://example.com/image.png)" />,
    );
    expect(screen.getByText("Extracted diagram")).toBeTruthy();
    expect(container.querySelector("img")).toBeNull();
  });

  it("handles empty content", () => {
    render(<MarkdownDocumentViewer content="" />);
    expect(screen.getByText("No text content available.")).toBeTruthy();
  });

  it("renders large documents with duplicate dividers in virtualized mode without key warnings", () => {
    const errorSpy = vi.spyOn(console, "error").mockImplementation(() => {});
    const scrollElement = document.createElement("div");
    Object.defineProperty(scrollElement, "clientHeight", { value: 600 });
    Object.defineProperty(scrollElement, "scrollHeight", { value: 2000 });
    Object.defineProperty(scrollElement, "offsetHeight", { value: 600 });
    Object.defineProperty(scrollElement, "offsetWidth", { value: 800 });
    scrollElement.getBoundingClientRect = () => ({
      width: 800,
      height: 600,
      top: 0,
      left: 0,
      bottom: 600,
      right: 800,
      x: 0,
      y: 0,
      toJSON: () => {},
    });

    // Generate 30 chunks with repeated '---' dividers and identical text
    const chunks: string[] = [];
    for (let i = 0; i < 15; i++) {
      chunks.push(`## Section ${i % 3}`);
      chunks.push("---");
    }
    const content = chunks.join("\n\n");

    const { container } = render(
      <MarkdownDocumentViewer content={content} scrollElement={scrollElement} />,
    );

    expect(container.querySelector("[data-index]")).not.toBeNull();

    const keyErrors = errorSpy.mock.calls.filter((args) =>
      args.some(
        (arg) => typeof arg === "string" && arg.includes("Encountered two children with the same key"),
      ),
    );
    expect(keyErrors).toHaveLength(0);

    errorSpy.mockRestore();
  });

  it("renders code blocks containing blank lines correctly", () => {
    const content = [
      "# Code Demo",
      "```typescript\nconst a = 1;\n\nconst b = 2;\nreturn a + b;\n```",
    ].join("\n\n");

    const { container } = render(<MarkdownDocumentViewer content={content} />);
    const code = container.querySelector("pre, code");
    expect(code).not.toBeNull();
    expect(code?.textContent).toContain("const b = 2;");
  });
});
